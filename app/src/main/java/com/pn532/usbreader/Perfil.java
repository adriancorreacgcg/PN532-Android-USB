package com.pn532.usbreader;

/** Perfil estático en modo banda (MSD) de la tarjeta donante. */
public final class Perfil {
    private Perfil() {}

    private static final byte[] PPSE = new byte[] {
        0x6F, 0x22, (byte) 0x84, 0x0E, 0x32, 0x50, 0x41, 0x59, 0x2E, 0x53,
        0x59, 0x53, 0x2E, 0x44, 0x44, 0x46, 0x30, 0x31,
        (byte) 0xA5, 0x10, (byte) 0xBF, 0x0C, 0x0E, 0x61, 0x0C, 0x4F, 0x07,
        (byte) 0xA0, 0x00, 0x00, 0x00, 0x04, 0x10, 0x10, (byte) 0x87, 0x01, 0x01,
        (byte) 0x90, 0x00
    };

    private static final byte[] FCI = new byte[] {
        0x6F, 0x29, (byte) 0x84, 0x07,
        (byte) 0xA0, 0x00, 0x00, 0x00, 0x04, 0x10, 0x10,
        (byte) 0xA5, 0x1E, 0x50, 0x10,
        0x44, 0x65, 0x62, 0x69, 0x74, 0x20, 0x4D, 0x61, 0x73, 0x74, 0x65,
        0x72, 0x63, 0x61, 0x72, 0x64,
        (byte) 0x87, 0x01, 0x01,
        (byte) 0x90, 0x00
    };

    /** Formato 1: AIP + pista 2 equivalente. Sin AFL, sin criptograma. */
    private static final byte[] GPO = new byte[] {
        (byte) 0x80, 0x10, 0x19, (byte) 0x80,
        0x55, 0x79, 0x07, 0x01, 0x61, 0x48, 0x35, 0x35, (byte) 0xD3,
        0x00, 0x32, 0x01, (byte) 0x94, 0x2F,
        (byte) 0x90, 0x00
    };

    private static final byte[] GENAC = new byte[] {
        0x77, 0x1E, (byte) 0x9F, 0x27, 0x01, (byte) 0x80,
        (byte) 0x9F, 0x36, 0x02, 0x00, 0x01,
        (byte) 0x9F, 0x26, 0x08, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, (byte) 0x88,
        (byte) 0x9F, 0x10, 0x07, 0x06, 0x0A, 0x03, (byte) 0xA0, 0x00, 0x00, 0x00,
        (byte) 0x90, 0x00
    };

    private static final byte[] NO_ENCONTRADO = new byte[] { 0x6A, (byte) 0x82 };
    private static final byte[] NO_SOPORTADO = new byte[] { 0x6D, 0x00 };

    public static byte[] responder(byte[] apdu) {
        if (apdu.length < 4) return NO_SOPORTADO;
        int ins = apdu[1] & 0xff;
        if (ins == 0xA4) {
            if (contiene(apdu, "2PAY.SYS.DDF01")) return PPSE;
            if (contiene(apdu, "\u00A0\u0000\u0000\u0000\u0004\u0010\u0010")) return FCI;
            return NO_ENCONTRADO;
        }
        if (ins == 0xA8) return GPO;
        if (ins == 0xB2) return NO_ENCONTRADO;
        if (ins == 0xAE) return GENAC;
        return NO_SOPORTADO;
    }

    private static boolean contiene(byte[] datos, String texto) {
        byte[] busca = texto.getBytes();
        for (int i = 0; i + busca.length <= datos.length; i++) {
            boolean ok = true;
            for (int j = 0; j < busca.length; j++) {
                if (datos[i + j] != busca[j]) { ok = false; break; }
            }
            if (ok) return true;
        }
        return false;
    }
}